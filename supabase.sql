-- 1. Crear la tabla de favoritos vinculada al usuario autenticado (auth.users)
create table public.favoritos (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) not null default auth.uid(),
  character_id integer not null,
  name text not null,
  status text,
  species text,
  image_url text, -- Aquí guardaremos la ruta de la foto (Opción B)
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Habilitar RLS (Row Level Security) obligatorio por la consigna
alter table public.favoritos enable row level security;

-- 3. Políticas de seguridad: Cada usuario solo ve, crea y borra lo suyo
create policy "Usuarios pueden ver sus propios favoritos"
  on public.favoritos for select
  using (auth.uid() = user_id);

create policy "Usuarios pueden insertar sus propios favoritos"
  on public.favoritos for insert
  with check (auth.uid() = user_id);

create policy "Usuarios pueden borrar sus propios favoritos"
  on public.favoritos for delete
  using (auth.uid() = user_id);